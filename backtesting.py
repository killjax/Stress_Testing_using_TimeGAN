"""backtesting.py

Trading Strategy Stress-Testing & Backtesting Framework for TimeGAN.
Evaluates benchmark algorithmic trading strategies across Real and Synthetic
market regimes (Normal, Volatile, Crisis) generated by TimeGAN.
"""

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns

from data_loading import DEFAULT_FEATURE_NAMES

TRADING_DAYS_PER_YEAR = 252.0


def generate_strategy_positions(window, strategy_name, feature_names=None):
    """Computes causal (t-1 -> t) daily portfolio weights for a given strategy.

    All signals are lagged by 1 time step (`pos[t]` depends only on information
    up to `t - 1`) to prevent lookahead bias.

    Args:
        window (np.ndarray): Single sequence of shape (seq_len, dim).
        strategy_name (str): One of 'Buy & Hold', 'MACD Crossover',
            'RSI Mean-Reversion', or 'Volatility Target'.
        feature_names (list[str], optional): Column names.

    Returns:
        np.ndarray: 1D array of portfolio weights of length `seq_len`.
    """
    if feature_names is None:
        feature_names = DEFAULT_FEATURE_NAMES

    idx = {name: i for i, name in enumerate(feature_names)}
    T = len(window)
    positions = np.zeros(T, dtype=np.float64)
    if T == 0:
        return positions

    if strategy_name == "Buy & Hold":
        positions[:] = 1.0
        return positions

    elif strategy_name == "MACD Crossover":
        macd = window[:, idx["MACD"]]
        signal = window[:, idx["MACD_Signal"]]
        # Long (1.0) when yesterday's MACD > MACD_Signal, else Cash (0.0)
        raw_sig = (macd > signal).astype(np.float64)
        positions[1:] = raw_sig[:-1]
        positions[0] = 0.0
        return positions

    elif strategy_name == "RSI Mean-Reversion":
        rsi = window[:, idx["RSI"]]
        # Enter Long (1.0) when RSI < 35 (oversold), exit (0.0) when RSI > 65 (overbought)
        curr_pos = 0.0
        for t in range(1, T):
            prev_rsi = rsi[t - 1]
            if prev_rsi < 35.0:
                curr_pos = 1.0
            elif prev_rsi > 65.0:
                curr_pos = 0.0
            positions[t] = curr_pos
        return positions

    elif strategy_name == "Volatility Target":
        # Trend + Volatility-managed strategy: scales exposure inversely with BBW / trailing vol
        macd = window[:, idx["MACD"]]
        signal = window[:, idx["MACD_Signal"]]
        bbw = np.maximum(window[:, idx["BBW"]], 1e-3)
        target_bbw = 0.08
        raw_weight = np.clip(target_bbw / bbw, 0.2, 1.5)
        trend_filter = (macd >= signal).astype(np.float64)
        # Lag by 1 step for causal execution
        positions[1:] = raw_weight[:-1] * trend_filter[:-1]
        positions[0] = 0.0
        return positions

    else:
        raise ValueError(
            f"Unknown strategy '{strategy_name}'. Supported: "
            "['Buy & Hold', 'MACD Crossover', 'RSI Mean-Reversion', 'Volatility Target']"
        )


def compute_sequence_performance(
    window,
    strategy_name,
    feature_names=None,
    transaction_cost_bps=5.0,
    risk_free_rate=0.0,
):
    """Evaluates a trading strategy on a single (seq_len, dim) window.

    Uses the window's `Log_Return` series (clipped to realistic daily bounds)
    to construct a scale-invariant return and equity curve.

    Args:
        window (np.ndarray): 2D array of shape (seq_len, dim).
        strategy_name (str): Strategy identifier.
        feature_names (list[str], optional): Column names.
        transaction_cost_bps (float): One-way transaction cost in basis points (default: 5 bps).
        risk_free_rate (float): Annualized risk-free rate (default: 0.0).

    Returns:
        dict: Performance and tail-risk metrics for the sequence.
    """
    if feature_names is None:
        feature_names = DEFAULT_FEATURE_NAMES

    w = np.asarray(window, dtype=np.float64)
    idx = {name: i for i, name in enumerate(feature_names)}

    # Extract daily log returns and convert to simple arithmetic returns
    log_ret = np.clip(w[:, idx["Log_Return"]], -0.35, 0.35)
    simple_ret = np.expm1(log_ret)

    positions = generate_strategy_positions(w, strategy_name, feature_names)

    # Turnover & transaction costs
    turnover = np.abs(np.diff(positions, prepend=0.0))
    cost = turnover * (transaction_cost_bps * 1e-4)

    strat_ret = positions * simple_ret - cost

    # Equity curve starting at 1.0
    equity = np.cumprod(1.0 + strat_ret)
    total_return = float(equity[-1] - 1.0) if len(equity) > 0 else 0.0

    n_days = max(1, len(strat_ret))
    ann_return = float((1.0 + max(total_return, -0.9999)) ** (TRADING_DAYS_PER_YEAR / n_days) - 1.0)

    daily_mean = float(np.mean(strat_ret))
    daily_std = float(np.std(strat_ret))
    ann_vol = float(daily_std * np.sqrt(TRADING_DAYS_PER_YEAR))

    daily_rf = risk_free_rate / TRADING_DAYS_PER_YEAR
    excess_ret = strat_ret - daily_rf

    if daily_std > 1e-8:
        sharpe = float((np.mean(excess_ret) / daily_std) * np.sqrt(TRADING_DAYS_PER_YEAR))
    else:
        sharpe = 0.0

    downside_ret = np.minimum(excess_ret, 0.0)
    downside_std = float(np.sqrt(np.mean(downside_ret**2)))
    if downside_std > 1e-8:
        sortino = float((np.mean(excess_ret) / downside_std) * np.sqrt(TRADING_DAYS_PER_YEAR))
    else:
        sortino = 0.0

    # Maximum Drawdown (MDD) on the strategy equity curve
    running_max = np.maximum.accumulate(np.insert(equity, 0, 1.0))
    eq_with_start = np.insert(equity, 0, 1.0)
    drawdowns = (running_max - eq_with_start) / (running_max + 1e-9)
    max_drawdown = float(np.max(drawdowns))

    calmar = float(ann_return / max_drawdown) if max_drawdown > 1e-4 else 0.0

    # Tail risk: Daily 95% VaR and 95% CVaR (Expected Shortfall, expressed as positive loss)
    q05 = float(np.percentile(strat_ret, 5.0))
    var_95 = float(-q05)
    tail_losses = strat_ret[strat_ret <= q05]
    cvar_95 = float(-np.mean(tail_losses)) if len(tail_losses) > 0 else var_95

    return {
        "total_return_pct": total_return * 100.0,
        "ann_return_pct": np.clip(ann_return * 100.0, -100.0, 500.0),
        "ann_vol_pct": ann_vol * 100.0,
        "sharpe_ratio": np.clip(sharpe, -10.0, 10.0),
        "sortino_ratio": np.clip(sortino, -15.0, 15.0),
        "max_drawdown_pct": max_drawdown * 100.0,
        "calmar_ratio": np.clip(calmar, -10.0, 10.0),
        "var_95_pct": var_95 * 100.0,
        "cvar_95_pct": cvar_95 * 100.0,
        "positive_window": 1.0 if total_return > 0.0 else 0.0,
    }


def evaluate_strategies_across_regimes(
    datasets_dict,
    feature_names=None,
    strategies=None,
    transaction_cost_bps=5.0,
    max_samples_per_regime=None,
    seed=42,
):
    """Evaluates multiple trading strategies across Real and Synthetic regime datasets.

    Args:
        datasets_dict (dict): Mapping of `(source_label, regime_label)` -> list of 2D windows,
            e.g., `{('Real', 'Normal'): ori_n, ('Synthetic', 'Normal'): gen_n, ...}`.
        feature_names (list[str], optional): Column names.
        strategies (list[str], optional): Strategy names to evaluate.
        transaction_cost_bps (float): Transaction cost in bps.
        max_samples_per_regime (int, optional): Optional cap on windows evaluated per regime.
        seed (int): Random seed for subsampling if `max_samples_per_regime` is set.

    Returns:
        tuple: (summary_df, detailed_df)
            summary_df (pd.DataFrame): Aggregated mean/median metrics grouped by
                (Strategy, Regime, Source).
            detailed_df (pd.DataFrame): Window-level metrics for statistical testing and plotting.
    """
    if strategies is None:
        strategies = [
            "Buy & Hold",
            "MACD Crossover",
            "RSI Mean-Reversion",
            "Volatility Target",
        ]

    rng = np.random.default_rng(seed)
    records = []

    for (source, regime), windows in datasets_dict.items():
        if windows is None or len(windows) == 0:
            continue

        n_win = len(windows)
        if max_samples_per_regime is not None and n_win > max_samples_per_regime:
            idx = rng.choice(n_win, size=max_samples_per_regime, replace=False)
            sampled_windows = [windows[i] for i in idx]
        else:
            sampled_windows = windows

        for strat in strategies:
            for w_idx, window in enumerate(sampled_windows):
                perf = compute_sequence_performance(
                    window,
                    strategy_name=strat,
                    feature_names=feature_names,
                    transaction_cost_bps=transaction_cost_bps,
                )
                perf["Source"] = source
                perf["Regime"] = regime
                perf["Strategy"] = strat
                perf["Window_ID"] = w_idx
                records.append(perf)

    detailed_df = pd.DataFrame(records)
    if detailed_df.empty:
        return pd.DataFrame(), detailed_df

    summary_df = (
        detailed_df.groupby(["Strategy", "Regime", "Source"], as_index=False)
        .agg(
            Samples=("Window_ID", "count"),
            Mean_Return_Pct=("total_return_pct", "mean"),
            Mean_Vol_Pct=("ann_vol_pct", "mean"),
            Mean_Sharpe=("sharpe_ratio", "mean"),
            Median_Sharpe=("sharpe_ratio", "median"),
            Mean_Sortino=("sortino_ratio", "mean"),
            Mean_MDD_Pct=("max_drawdown_pct", "mean"),
            P90_MDD_Pct=("max_drawdown_pct", lambda s: float(np.percentile(s, 90.0))),
            Mean_CVaR95_Pct=("cvar_95_pct", "mean"),
            Win_Rate_Pct=("positive_window", lambda s: float(np.mean(s) * 100.0)),
        )
        .round(3)
    )

    return summary_df, detailed_df


def plot_stress_test_comparison(
    detailed_df, save_path="stress_test_results.png", show=True
):
    """Generates a 2x2 stress-testing dashboard comparing Real vs. Synthetic regimes."""
    if detailed_df.empty:
        print("No backtesting records to plot.")
        return

    sns.set_theme(style="whitegrid")
    fig, axes = plt.subplots(2, 2, figsize=(16, 12))
    palette = {"Real": "#1f77b4", "Synthetic": "#ff7f0e"}
    regime_order = [
        r for r in ["Normal", "Volatile", "Crisis"] if r in detailed_df["Regime"].unique()
    ]

    # 1. Sharpe Ratio across Strategies & Sources (Crisis + Volatile Stress Regimes)
    stress_df = detailed_df[detailed_df["Regime"].isin(["Crisis", "Volatile"])]
    if stress_df.empty:
        stress_df = detailed_df
    sns.boxplot(
        data=stress_df,
        x="Strategy",
        y="sharpe_ratio",
        hue="Source",
        palette=palette,
        showfliers=False,
        ax=axes[0, 0],
    )
    axes[0, 0].axhline(0.0, color="red", linestyle="--", alpha=0.6)
    axes[0, 0].set_title("Stress Regimes (Crisis & Volatile): Sharpe Ratio by Strategy", fontsize=13)
    axes[0, 0].set_xlabel("")
    axes[0, 0].set_ylabel("Sharpe Ratio")
    axes[0, 0].tick_params(axis="x", rotation=15)

    # 2. Maximum Drawdown (%) across Regimes
    sns.boxplot(
        data=detailed_df,
        x="Regime",
        y="max_drawdown_pct",
        hue="Source",
        order=regime_order,
        palette=palette,
        showfliers=False,
        ax=axes[0, 1],
    )
    axes[0, 1].set_title("Maximum Drawdown (%) Across Market Regimes", fontsize=13)
    axes[0, 1].set_xlabel("Market Regime")
    axes[0, 1].set_ylabel("Maximum Drawdown (%)")

    # 3. Mean Strategy Sharpe Ratio by Regime (Synthetic Stress Test)
    synth_df = detailed_df[detailed_df["Source"] == "Synthetic"]
    if synth_df.empty:
        synth_df = detailed_df
    sns.barplot(
        data=synth_df,
        x="Strategy",
        y="sharpe_ratio",
        hue="Regime",
        hue_order=regime_order,
        palette={"Normal": "#2ca02c", "Volatile": "#1f77b4", "Crisis": "#d62728"},
        errorbar=("ci", 95),
        ax=axes[1, 0],
    )
    axes[1, 0].axhline(0.0, color="black", linestyle="--", alpha=0.6)
    axes[1, 0].set_title("Synthetic Stress Test: Strategy Sharpe Ratio by Regime", fontsize=13)
    axes[1, 0].set_xlabel("")
    axes[1, 0].set_ylabel("Mean Sharpe Ratio (95% CI)")
    axes[1, 0].tick_params(axis="x", rotation=15)

    # 4. Daily 95% Expected Shortfall (CVaR_95) by Strategy under Crisis
    crisis_df = detailed_df[detailed_df["Regime"] == "Crisis"]
    if crisis_df.empty:
        crisis_df = detailed_df
    sns.barplot(
        data=crisis_df,
        x="Strategy",
        y="cvar_95_pct",
        hue="Source",
        palette=palette,
        errorbar=("ci", 95),
        ax=axes[1, 1],
    )
    axes[1, 1].set_title("Crisis Regime Tail Risk: Daily 95% CVaR (Expected Shortfall %)", fontsize=13)
    axes[1, 1].set_xlabel("")
    axes[1, 1].set_ylabel("Daily 95% CVaR Loss (%)")
    axes[1, 1].tick_params(axis="x", rotation=15)

    plt.suptitle(
        "Trading Strategy Stress-Testing Framework: Real vs. TimeGAN Synthetic Scenarios",
        fontsize=16,
        fontweight="bold",
        y=1.01,
    )
    plt.tight_layout()
    if save_path:
        plt.savefig(save_path, bbox_inches="tight", dpi=150)
        print(f"Saved stress-testing comparison figure to '{save_path}'")
    if show:
        plt.show()
    else:
        plt.close(fig)

